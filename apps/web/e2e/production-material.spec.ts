import { expect, test } from "@playwright/test";
import { randomUUID } from "node:crypto";
import { ProductionMaterialsWorkspaceSchema } from "@yummyai/contracts/order/material-execution";
import { prepareNativeProduction } from "./native-production-fixture";
import { centerApi } from "./order-centers-fixture";
import { loginErp } from "./erp-identity-fixture";

test("personal material operations preserve drafts and recover an original committed consumption in a fresh session", async ({ page, browser }, info) => {
  test.setTimeout(240_000);
  const data = await prepareNativeProduction(), errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.setViewportSize({ width: 1440, height: 1000 });
  await loginErp(page, "operator", `/production?view=native&line=${data.lineId}`);
  const productionForm = page.getByRole("form", { name: "建立直接生产安排", exact: true });
  await productionForm.getByLabel("完整产品规格", { exact: true }).selectOption(data.specificationVersionId);
  await productionForm.getByLabel("已审核设计", { exact: true }).selectOption(data.designVersionId);
  await productionForm.getByLabel("已批准采购来源", { exact: true }).selectOption(`${data.routingDecisionId}:${data.purchaseOrderVersionId}`);
  await productionForm.getByLabel("制造版本", { exact: true }).selectOption(data.manufacturing.versionId);
  await productionForm.getByRole("checkbox", { name: /已核对原规格/ }).check();
  await productionForm.getByLabel("生产工厂", { exact: true }).selectOption(data.capabilityVersionId);
  const due = new Date(Date.now() + 3 * 86400_000);
  await productionForm.locator('input[name="due"]').fill(new Date(due.getTime() - due.getTimezoneOffset() * 60000).toISOString().slice(0, 16));
  await productionForm.getByLabel("本次产品及设计确认依据", { exact: true }).fill("Synthetic current product and design reviewed for material execution");
  await productionForm.getByLabel("本次生产说明", { exact: true }).fill("Synthetic material flow only No factory handover");
  await productionForm.getByRole("checkbox", { name: /已核对完整产品规格/ }).check();
  await productionForm.getByRole("button", { name: "建立内部生产安排", exact: true }).click();
  const productionRecovery = page.getByRole("region", { name: "待确认生产提交", exact: true });
  await expect(productionRecovery).toContainText("生产安排已建立");
  await productionRecovery.getByRole("button", { name: "已核对本次结果", exact: true }).click();
  const detailResponse = await page.request.get(`/api/order-centers/native/lines/${data.lineId}`);
  expect(detailResponse.ok()).toBe(true); const production = (await detailResponse.json()).productions[0].id as string;
  const workspace = async () => { const response = await page.request.get(`/api/production-materials/${production}`); expect(response.ok()).toBe(true); return ProductionMaterialsWorkspaceSchema.parse(await response.json()); }, original = await workspace();
  const stockId = original.lines[0]!.stockItemId, suffix = randomUUID().slice(0, 8).toUpperCase();
  const warehouse = await centerApi<{ id: string }>("inventory/warehouses", { code: `MAT-${suffix}`, name: `Synthetic material warehouse ${suffix}`, type: "owned", countryCode: "US", timeZone: "America/New_York" });
  const location = await centerApi<{ id: string }>("inventory/locations", { warehouseId: warehouse.id, code: `BIN-${suffix}`, name: `Synthetic material bin ${suffix}` });
  await centerApi("inventory/movements", { stockItemId: stockId, locationId: location.id, lotId: null, quantityDelta: 2, unit: "meter", bucket: "physical", type: "opening", sourceType: "opening", sourceId: data.lineId,
    reasonCode: "SYNTHETIC_OPENING", occurredAt: new Date().toISOString(), idempotencyKey: randomUUID() });
  const panel = page.getByRole("region", { name: "原生产备料与实际耗用", exact: true });
  await panel.getByRole("button", { name: "备料与实际耗用", exact: true }).click();
  await panel.getByRole("button", { name: "备料预留", exact: true }).click();
  const reserve = panel.getByRole("form", { name: "备料预留", exact: true });
  await expect(reserve.getByLabel("库位与批次", { exact: true }).getByRole("option")).toHaveCount(2);
  await reserve.getByLabel("库位与批次", { exact: true }).selectOption(`${stockId}:${location.id}:-`);
  await reserve.getByLabel("本次数量", { exact: true }).fill("0.4");
  await reserve.getByRole("button", { name: "备料预留", exact: true }).click();
  const recovery = panel.getByRole("region", { name: "待确认物料提交", exact: true });
  await expect(recovery).toContainText("实际物料已记录");
  await recovery.getByRole("button", { name: "已核对本次结果", exact: true }).click();
  await expect(recovery).toHaveCount(0);
  const reserved = (await workspace()).entries.find(entry => entry.kind === "reserve")!;
  await panel.getByRole("button", { name: "记录实际耗用", exact: true }).click();
  const form = panel.getByRole("form", { name: "记录实际耗用", exact: true });
  await expect(form.getByLabel("耗用来源", { exact: true }).getByRole("option")).toHaveCount(2);
  await form.getByLabel("耗用来源", { exact: true }).selectOption(reserved.id);
  await form.getByLabel("本次数量", { exact: true }).fill("0.123456789");
  await form.getByRole("checkbox", { name: "已确认本次实际领用数量与原库位批次", exact: true }).check();
  const submit = form.getByRole("button", { name: "记录实际耗用", exact: true });
  await expect(submit).toBeEnabled();
  const originalUrl = page.url();
  page.once("dialog", dialog => dialog.dismiss());
  await page.getByRole("link", { name: "审核稿生产", exact: true }).click();
  await expect(page).toHaveURL(originalUrl); await expect(form.getByLabel("本次数量", { exact: true })).toHaveValue("0.123456789");
  const stockReads = `**/api/production-materials/${production}/stock-options?*`;
  await page.route(stockReads, route => route.fulfill({ status: 503, contentType: "application/json", body: JSON.stringify({ message: "Synthetic temporary stock read outage" }) }));
  await form.getByRole("button", { name: "重新核对来源 保留填写", exact: true }).click();
  await expect(form).toContainText("Synthetic temporary stock read outage");
  await expect(submit).toBeDisabled(); await expect(form.getByLabel("本次数量", { exact: true })).toHaveValue("0.123456789");
  await page.unroute(stockReads); await form.getByRole("button", { name: "重新核对来源 保留填写", exact: true }).click();
  await expect(form.getByLabel("耗用来源", { exact: true })).toHaveValue(reserved.id); await expect(submit).toBeEnabled();
  await panel.scrollIntoViewIfNeeded(); await page.screenshot({ path: info.outputPath("material-form-desktop.png"), animations: "disabled", fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
  await page.screenshot({ path: info.outputPath("material-form-mobile.png"), animations: "disabled", fullPage: true });
  let writes = 0;
  await page.route(`**/api/production-materials/${production}/commands/*/execute`, async route => {
    writes++; expect(route.request().postDataJSON()).toEqual({});
    const response = await route.fetch(); expect(response.ok()).toBe(true); expect((await response.json()).status).toBe("succeeded"); await route.abort("failed");
  });
  await submit.click(); await expect(recovery).toContainText("实际物料已记录"); expect(writes).toBe(1);
  const consumed = (await workspace()).entries.filter(entry => entry.kind === "consume"); expect(consumed).toHaveLength(1); expect(consumed[0]!.quantity).toBe("0.123456789");
  const context = await browser.newContext({ baseURL: String(info.project.use.baseURL), viewport: { width: 1440, height: 1000 } });
  try {
    const fresh = await context.newPage(); fresh.on("pageerror", error => errors.push(error.message));
    await loginErp(fresh, "operator", `/production?view=native&line=${data.lineId}`);
    const restored = fresh.getByRole("region", { name: "原生产备料与实际耗用", exact: true });
    await restored.getByRole("button", { name: "备料与实际耗用", exact: true }).click();
    const result = restored.getByRole("region", { name: "待确认物料提交", exact: true });
    await expect(result).toContainText(consumed[0]!.id); await expect(result).toContainText("0.123456789");
    await expect(result.getByRole("button", { name: "按原填写记录", exact: true })).toHaveCount(0);
    await result.getByRole("button", { name: "已核对本次结果", exact: true }).click(); await expect(result).toHaveCount(0);
    await restored.getByRole("button", { name: "登记原耗用实物退料", exact: true }).click();
    const returned = restored.getByRole("form", { name: "记录实际退料", exact: true });
    await expect(returned).toContainText(`Synthetic material bin ${suffix}`);
    await returned.getByLabel("本次数量", { exact: true }).fill("0.023456789");
    await returned.getByLabel("原因或说明", { exact: true }).fill("Synthetic confirmed return to the original material bin");
    await returned.getByRole("checkbox", { name: "已确认实物实际退回原库位与原批次", exact: true }).check();
    await returned.getByRole("button", { name: "记录实际退料", exact: true }).click(); await expect(result).toContainText("实际物料已记录");
    await result.getByRole("button", { name: "已核对本次结果", exact: true }).click(); await expect(result).toHaveCount(0);
    expect((await workspace()).lines[0]!.actualNetQuantity).toBe("0.1");
    await fresh.screenshot({ path: info.outputPath("material-original-return-desktop.png"), animations: "disabled", fullPage: true });
  } finally { await context.close(); }
  expect((await workspace()).entries.filter(entry => entry.kind === "consume")).toHaveLength(1); expect(errors).toEqual([]);
});

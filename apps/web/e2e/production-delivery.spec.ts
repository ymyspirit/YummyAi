async function openReply(form: Locator) {
  const details = form.locator("xpath=ancestor::details[1]"), summary = details.locator(":scope > summary");
  await expect(summary).toHaveText(/^(登记真实文件提交凭据|可选补充回执与异常处理)$/);
  if (await details.getAttribute("open") === null) await summary.click();
  await expect(form).toBeVisible();
}
async function fillReply(form: Locator, reference: string, note: string) {
  await openReply(form);
  const submitted = await form.getByRole("combobox", { name: "回执类型", exact: true }).inputValue() === "submitted";
  await form.getByLabel(submitted ? "提交凭证依据" : "回复依据", { exact: true }).fill(reference);
  await form.getByLabel(submitted ? "文件提交说明" : "工厂回复与处理说明", { exact: true }).fill(note);
  await form.getByRole("checkbox", { name: submitted ? "我已核对真实文件提交凭据 文件及制造清单校验值" : "我已核对工厂实际回复、文件及制造清单校验值", exact: true }).check();
}

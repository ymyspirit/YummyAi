test("production delivery splits a complete order into factory-specific packages", async ({ page }, testInfo) => {
  test.setTimeout(180000);
  const order = await prepareDeliveryOrder(2, true); await loginErp(page, "operator", `/production?q=${order.externalId}&line=${order.lines[0]}`);
  await page.locator("summary").filter({ hasText: /^工厂交付与回执/ }).click();
  const panel = page.getByRole("region", { name: "抱枕交付与工厂回执", exact: true });
  await expect(panel).toContainText("本单由多个工厂生产");
  for (const factory of order.factories) {
    await panel.getByLabel("交付工厂", { exact: true }).selectOption(factory.id);
    await expect(panel.getByRole("checkbox", { name: new RegExp(`选择交付 ${order.externalId}`) })).toBeChecked();
    await panel.getByRole("button", { name: "生成本工厂交付包（1）", exact: true }).click();
    await expect(panel.getByRole("status").filter({ hasText: "正式交付包已锁定" })).toBeVisible();
  }
  await expect(panel.locator("details.oc-delivery-package")).toHaveCount(2);
  const detail = await centerApi<OrderWorkDetail>(`order-centers/lines/${order.lines[0]}`);
  const view = await centerApi<ProductionDeliveryWorkspace>(`order-centers/deliveries?order=${detail.line.orderId}`);
  expect(view.packages).toHaveLength(2);
  expect(new Set(view.packages.map(packet => packet.factory!.factoryId)).size).toBe(2);
  expect(view.packages.every(packet => packet.items.length === 1 && packet.items[0]!.snapshot!.quantity === 2)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath("factory-split-delivery.png"), fullPage: true });
});
